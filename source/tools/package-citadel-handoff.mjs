import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import JSZip from 'jszip';
const root='outputs/canyon-citadel-showcase-v1';
const receipt='outputs-desktop-test-eb4kBk';
const destination='outputs/Canyon-Citadel-v1-private-handoff.zip';
assert.equal(fs.existsSync(destination),false,'Preserve prior handoff');
const report=JSON.parse(fs.readFileSync(`${receipt}/report.json`));
assert.equal(report.passed,true);
const digest=b=>createHash('sha256').update(b).digest('hex');
assert.equal(report.fixtureSha256,digest(fs.readFileSync(`${root}/Canyon-Citadel-v1.zip`)));
assert.equal(report.executableSha256,digest(fs.readFileSync('dist/desktop/win-x64/WulframForge.exe')));
for(const name of ['routes','cover'])assert.equal(JSON.parse(fs.readFileSync(`${root}/${name}.json`)).passed,true);
assert.equal(JSON.parse(fs.readFileSync(`${root}/analysis.json`)).analysis.passed,true);
const zip=new JSZip();
for(const name of fs.readdirSync(root))if(fs.statSync(path.join(root,name)).isFile())zip.file(name,fs.readFileSync(path.join(root,name)));
for(const name of fs.readdirSync(receipt))if(name.endsWith('.png'))zip.file(`screenshots/${name}`,fs.readFileSync(path.join(receipt,name)));
zip.file('editor-test-receipt.json',fs.readFileSync(`${receipt}/report.json`));
for(const name of ['verify-citadel-routes.mjs','verify-citadel-cover.mjs'])zip.file(`verification-source/${name}`,fs.readFileSync(`tools/${name}`));
const bytes=await zip.generateAsync({type:'nodebuffer',compression:'DEFLATE'});
await JSZip.loadAsync(bytes,{checkCRC32:true});
fs.writeFileSync(destination,bytes);
fs.writeFileSync('outputs/Canyon-Citadel-v1-private-handoff-SHA256SUMS.txt',`${digest(bytes)}  ${path.basename(destination)}\n`);
console.log(JSON.stringify({destination,sha256:digest(bytes),mapMatchesTest:true,zipCRC:true}));
